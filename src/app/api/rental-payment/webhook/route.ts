import Stripe from "stripe"
import { NextResponse } from "next/server"
import { sendEmail } from "@/lib/mailer"
import { appendLead } from "@/lib/leads-store"
import {
  getRentalByStripeCustomer,
  insertActiveRental,
  logRentalEmail,
  upsertDispute,
} from "@/lib/db"
import { SITE_EMAIL, SITE_PHONE } from "@/data/site"
import { escapeHtml as esc } from "@/lib/html"

export const runtime = "nodejs"

export async function POST(req: Request) {
  // Constructed per-request rather than at module scope: Next.js evaluates
  // route modules during the build's page-data collection, and the Stripe
  // SDK throws immediately if no key is configured yet.
  const stripe = new Stripe(process.env.STRIPE_SECRET_KEY || "", {
    apiVersion: "2026-07-29.dahlia",
  })

  const body = await req.text()
  const sig = req.headers.get("stripe-signature") || ""

  let event: Stripe.Event
  try {
    event = stripe.webhooks.constructEvent(
      body,
      sig,
      process.env.STRIPE_WEBHOOK_SECRET || ""
    )
  } catch (err) {
    const message = err instanceof Error ? err.message : "Unknown error"
    console.error("Webhook sig failed:", message)
    return NextResponse.json({ error: "Invalid signature" }, { status: 400 })
  }

  if (event.type === "charge.succeeded") {
    await sendRentalReceipt(stripe, event.data.object)
    return NextResponse.json({ received: true })
  }

  if (
    event.type === "charge.dispute.created" ||
    event.type === "charge.dispute.updated" ||
    event.type === "charge.dispute.closed"
  ) {
    try {
      await recordDispute(stripe, event.data.object, event.type === "charge.dispute.created")
    } catch (e) {
      // 500 so Stripe retries — a dispute that never reaches the table has
      // a deadline nobody is watching.
      console.error("Dispute webhook error:", e)
      return NextResponse.json({ error: "Dispute not recorded" }, { status: 500 })
    }
    return NextResponse.json({ received: true })
  }

  const meta = (event.data.object as Stripe.PaymentIntent).metadata || {}

  if (event.type === "payment_intent.succeeded") {
    const pi = event.data.object as Stripe.PaymentIntent

    // Weekly recurring invoice charges auto-generated by the Stripe
    // subscription land here too, and Stripe does not copy Subscription
    // metadata onto those PaymentIntents — so this event can legitimately
    // arrive with no usable metadata. Skip the emails rather than sending
    // "undefined" everywhere, but still log it so a real gap is visible.
    const hasValidMeta = Boolean(
      meta.customerName && meta.customerEmail && meta.vehicleName
    )
    if (!hasValidMeta) {
      console.error(
        "payment_intent.succeeded fired with incomplete metadata — skipping emails. PI id:",
        pi.id,
        "metadata:",
        meta
      )
      return NextResponse.json({ received: true, warning: "incomplete metadata" })
    }

    const isBondCharge = meta.paymentType === "bond"
    const bondWeeksLabel = meta.bondWeeks
      ? `${meta.bondWeeks} week${meta.bondWeeks === "1" ? "" : "s"}`
      : "2 weeks"

    try {
      await sendEmail(
        SITE_EMAIL,
        isBondCharge
          ? `✅ BOND RECEIVED — ${meta.vehicleName} — ${meta.customerName}`
          : `✅ PAYMENT RECEIVED — ${meta.vehicleName} — ${meta.customerName}`,
        `<div style="font-family:Arial;max-width:600px;margin:0 auto">
          <div style="background:#0f6e56;padding:20px;text-align:center">
            <h1 style="color:white;margin:0">${isBondCharge ? "✅ Bond Received" : "✅ Payment Received"}</h1>
          </div>
          <div style="padding:24px">
            <h3 style="color:#0f6e56">$${(pi.amount / 100).toFixed(2)} AUD received</h3>
            <table style="width:100%;border-collapse:collapse">
              ${[
                ["Customer", meta.customerName],
                ["Email", meta.customerEmail],
                ["Phone", meta.customerPhone],
                ["Vehicle", meta.vehicleName],
                ["Rego", meta.vehicleRego],
                ["Weekly Rent", `$${meta.weeklyRent}`],
                [`Bond (${bondWeeksLabel})`, `$${meta.bondAmount}`],
                ["Total Charged", `$${meta.totalCharged}`],
                ["Stripe ID", pi.id],
              ]
                .map(
                  ([k, v]) => `
                <tr>
                  <td style="padding:8px;background:#f8f8f8;font-size:12px;font-weight:bold;color:#666;width:35%;border-bottom:1px solid #eee">${k}</td>
                  <td style="padding:8px;font-size:14px;color:#1a1a2e;border-bottom:1px solid #eee">${esc(v)}</td>
                </tr>`
                )
                .join("")}
            </table>
            ${
              meta.bondPaidOnline === "true"
                ? `<div style="background:#e1f5ee;border-radius:8px;padding:12px;margin-top:12px">
                    <p style="margin:0;color:#085041;font-size:13px;font-weight:bold">
                      ✅ Bond paid online — no bond collection needed at pickup.
                    </p>
                  </div>`
                : `<div style="background:#fff3cd;border-radius:8px;padding:12px;margin-top:12px">
                    <p style="margin:0;color:#856404;font-size:13px;font-weight:bold">
                      ⚠️ Bond NOT paid online — collect $${(Number(meta.weeklyRent) * 2).toFixed(2)} bond in person at vehicle pickup.
                    </p>
                  </div>`
            }
            <div style="background:#e1f5ee;border-radius:8px;padding:14px;margin-top:16px">
              <p style="margin:0;color:#085041;font-weight:bold">
                ${
                  isBondCharge
                    ? `Bond secured for ${esc(meta.customerName)} — no further action needed for pickup arrangements.`
                    : `Next: Call ${esc(meta.customerName)} on ${esc(meta.customerPhone)} to arrange vehicle pickup.`
                }
              </p>
            </div>
          </div>
        </div>`
      )
    } catch (e) {
      console.error("Admin email:", e)
    }

    try {
      await sendEmail(
        meta.customerEmail,
        isBondCharge
          ? `✅ Bond Payment Confirmed — Pak Oz Rentals`
          : `✅ Payment Confirmed — Pak Oz Rentals`,
        `<div style="font-family:Arial;max-width:600px;margin:0 auto">
          <div style="background:#0f6e56;padding:20px;text-align:center">
            <h1 style="color:white;margin:0">${isBondCharge ? "Bond Payment Confirmed ✅" : "Payment Confirmed ✅"}</h1>
            <p style="color:#a8e6cf;margin:4px 0 0">Pak Oz Rentals · Brisbane</p>
          </div>
          <div style="padding:24px">
            <p>Hi ${(meta.customerName || "").split(" ")[0]},</p>
            <p>${
              isBondCharge
                ? "Your security bond payment has been received."
                : "Your payment has been received. We will contact you within 2 hours to arrange vehicle pickup."
            }</p>
            <div style="background:#f8f8f8;border-radius:12px;padding:16px;margin:16px 0">
              <h3 style="color:#1a1a2e;margin:0 0 12px">Payment Summary</h3>
              <table style="width:100%">
                ${[
                  ["Vehicle", meta.vehicleName],
                  ["Registration", meta.vehicleRego],
                  ...(isBondCharge
                    ? []
                    : [["Weekly Rent", `$${meta.weeklyRent}/week`]]),
                  isBondCharge
                    ? [`Security Bond (${bondWeeksLabel})`, `$${meta.bondAmount}, refundable`]
                    : ["Security Bond", `$${meta.bondAmount} (${bondWeeksLabel}, refundable)`],
                  ["Total Charged", `$${meta.totalCharged} AUD`],
                ]
                  .map(
                    ([k, v]) => `
                  <tr>
                    <td style="padding:7px 0;font-size:13px;color:#666;width:45%">${k}</td>
                    <td style="padding:7px 0;font-size:13px;font-weight:600;color:#1a1a2e">${v}</td>
                  </tr>`
                  )
                  .join("")}
              </table>
            </div>
            ${
              meta.bondPaidOnline === "true"
                ? `<div style="background:#e1f5ee;border-radius:8px;padding:14px;margin:16px 0">
                    <p style="margin:0;color:#085041;font-size:13px">
                      <strong>Bond:</strong> Your security bond has been paid and will be refunded in full at the end of your rental, provided no damage occurs.
                    </p>
                  </div>`
                : `<div style="background:#fff3cd;border-radius:8px;padding:14px;margin:16px 0">
                    <p style="margin:0;color:#856404;font-size:13px">
                      <strong>Bond due at pickup:</strong> Please bring $${(Number(meta.weeklyRent) * 2).toFixed(2)} for the security bond when you collect your vehicle. This is fully refundable at the end of your rental.
                    </p>
                  </div>`
            }
            <p style="color:#666;font-size:13px">
              Questions? Call us:<br/>
              <strong style="color:#7f85f7;font-size:16px">${SITE_PHONE}</strong>
            </p>
          </div>
        </div>`
      )
      if (meta.rentalId) {
        await logRentalEmail(
          meta.rentalId,
          isBondCharge ? "bond_confirmation" : "payment_confirmation",
          meta.customerEmail,
          isBondCharge ? "✅ Bond Payment Confirmed — Pak Oz Rentals" : "✅ Payment Confirmed — Pak Oz Rentals",
        ).catch((e) => console.error("Email log:", e))
      }
    } catch (e) {
      console.error("Customer email:", e)
    }

    try {
      await appendLead({
        id: pi.id,
        name: meta.customerName || "",
        phone: meta.customerPhone || "",
        email: meta.customerEmail || "",
        service: "car-rental",
        message: `${meta.vehicleName} (${meta.vehicleRego}) — $${meta.totalCharged} received by card`,
        date: new Date().toISOString(),
        status: "Won",
        page: "/services/car-rental",
        source: "quote_form",
      })
    } catch (e) {
      console.error("Lead save:", e)
    }

    // active_rentals drives the bank-transfer reminder email ("pay to BSB…").
    // A bond belongs to a Stripe subscription that bills itself and gets its
    // own pre-charge reminder, so it must not land in that table.
    try {
      if (!isBondCharge) await insertActiveRental({
        id: pi.id,
        vehicleId: meta.vehicleId || "",
        vehicleName: meta.vehicleName || "",
        vehicleRego: meta.vehicleRego || "",
        customerName: meta.customerName || "",
        customerEmail: meta.customerEmail || "",
        customerPhone: meta.customerPhone || "",
        weeklyRent: Number(meta.weeklyRent) || 0,
      })
    } catch (e) {
      console.error("Active rental save error:", e)
    }
  }

  if (event.type === "payment_intent.payment_failed") {
    const pi = event.data.object as Stripe.PaymentIntent
    const reason = pi.last_payment_error?.message || "Payment declined"

    try {
      await sendEmail(
        SITE_EMAIL,
        `❌ PAYMENT FAILED — ${meta.vehicleName} — ${meta.customerName}`,
        `<div style="font-family:Arial;max-width:600px;margin:0 auto">
          <div style="background:#c62828;padding:20px;text-align:center">
            <h1 style="color:white;margin:0">❌ Payment Failed</h1>
          </div>
          <div style="padding:24px">
            <p><strong>Customer:</strong> ${esc(meta.customerName)}</p>
            <p><strong>Email:</strong> ${esc(meta.customerEmail)}</p>
            <p><strong>Phone:</strong> ${esc(meta.customerPhone)}</p>
            <p><strong>Vehicle:</strong> ${meta.vehicleName} (${meta.vehicleRego})</p>
            <p><strong>Amount:</strong> $${meta.totalCharged}</p>
            <p><strong>Reason:</strong> ${reason}</p>
          </div>
        </div>`
      )
    } catch (e) {
      console.error("Admin fail email:", e)
    }

    try {
      await sendEmail(
        meta.customerEmail,
        `Payment unsuccessful — Pak Oz Rentals`,
        `<div style="font-family:Arial;max-width:600px;margin:0 auto">
          <div style="background:#c62828;padding:20px;text-align:center">
            <h1 style="color:white;margin:0">Payment Unsuccessful</h1>
          </div>
          <div style="padding:24px">
            <p>Hi ${(meta.customerName || "").split(" ")[0]},</p>
            <p>Unfortunately your payment of $${meta.totalCharged} could not be processed.</p>
            <p><strong>Reason:</strong> ${reason}</p>
            <div style="background:#f8f8f8;border-radius:12px;padding:16px;margin:16px 0">
              <p style="font-size:14px;color:#444;margin:0 0 10px">You can pay via direct bank transfer instead:</p>
              <table style="width:100%">
                ${[
                  ["Bank", "Westpac"],
                  ["Account Name", "Pak Oz Solutions Pty Ltd"],
                  ["BSB", "034-076"],
                  ["Account", "841442"],
                  ["PayID (ABN)", "53700444695"],
                  ["Amount", `$${meta.totalCharged} AUD`],
                  ["Reference", meta.vehicleRego],
                ]
                  .map(
                    ([k, v]) => `
                  <tr>
                    <td style="padding:6px 0;font-size:13px;color:#666;width:40%">${k}</td>
                    <td style="padding:6px 0;font-size:13px;font-weight:700;color:#1a1a2e">${v}</td>
                  </tr>`
                  )
                  .join("")}
              </table>
            </div>
            <p style="color:#666;font-size:13px">
              Call us for help:<br/>
              <strong style="color:#7f85f7;font-size:16px">${SITE_PHONE}</strong>
            </p>
          </div>
        </div>`
      )
    } catch (e) {
      console.error("Customer fail email:", e)
    }
  }

  return NextResponse.json({ received: true })
}

/**
 * Every successful rental charge (weekly invoice or bond) gets a Stripe
 * receipt. Setting receipt_email on a charge after the fact makes Stripe send
 * the receipt immediately — the weekly invoice charges are created by the
 * subscription, so this is the only place to set it on them.
 */
async function sendRentalReceipt(stripe: Stripe, charge: Stripe.Charge) {
  try {
    const customerId = typeof charge.customer === "string" ? charge.customer : charge.customer?.id
    if (!customerId) return
    const rental = await getRentalByStripeCustomer(customerId)
    if (!rental || !rental.customerEmail) return
    if (!charge.receipt_email) {
      await stripe.charges.update(charge.id, { receipt_email: rental.customerEmail })
    }
    await logRentalEmail(
      rental.id,
      "stripe_receipt",
      charge.receipt_email || rental.customerEmail,
      `Stripe receipt — $${(charge.amount / 100).toFixed(2)} ${charge.currency.toUpperCase()} (${charge.id})`,
    )
  } catch (e) {
    console.error("Receipt email error:", e)
  }
}

async function recordDispute(stripe: Stripe, dispute: Stripe.Dispute, isCreated: boolean) {
  const chargeId = typeof dispute.charge === "string" ? dispute.charge : dispute.charge.id
  const charge = await stripe.charges.retrieve(chargeId)
  const customerId = typeof charge.customer === "string" ? charge.customer : charge.customer?.id
  const rental = customerId ? await getRentalByStripeCustomer(customerId) : null
  const customerName = rental?.customerName || charge.billing_details?.name || "Unknown customer"
  const dueBy = dispute.evidence_details?.due_by
    ? new Date(dispute.evidence_details.due_by * 1000).toISOString()
    : null
  const amount = dispute.amount / 100

  const { created } = await upsertDispute({
    id: dispute.id,
    rentalId: rental?.id ?? null,
    chargeId,
    customerName,
    amount,
    currency: dispute.currency,
    reason: dispute.reason,
    status: dispute.status,
    dueBy,
  })

  // Stripe can deliver dispute.created more than once; email on first insert only.
  if (!isCreated || !created) return
  const deadline = dueBy
    ? new Date(dueBy).toLocaleString("en-AU", {
        timeZone: "Australia/Brisbane",
        dateStyle: "full",
        timeStyle: "short",
      }) + " (Brisbane)"
    : "Not given by Stripe — check the Stripe dashboard"
  try {
    await sendEmail(
      SITE_EMAIL,
      `⚠️ CHARGEBACK — $${amount.toFixed(2)} — ${customerName} — respond by ${dueBy ? new Date(dueBy).toLocaleDateString("en-AU", { timeZone: "Australia/Brisbane" }) : "ASAP"}`,
      `<div style="font-family:Arial;max-width:600px;margin:0 auto">
        <div style="background:#c62828;padding:20px;text-align:center">
          <h1 style="color:white;margin:0;font-size:20px">⚠️ New Chargeback / Dispute</h1>
        </div>
        <div style="padding:24px">
          <table style="width:100%;border-collapse:collapse">
            ${[
              ["Customer", customerName],
              ["Amount", `$${amount.toFixed(2)} ${dispute.currency.toUpperCase()}`],
              ["Reason", dispute.reason.replace(/_/g, " ")],
              ["Evidence deadline", deadline],
              ["Vehicle", rental ? `${rental.vehicleName} (${rental.vehicleRego})` : "Not linked to a rental"],
              ["Dispute ID", dispute.id],
            ]
              .map(
                ([k, v]) => `<tr>
                  <td style="padding:8px;background:#f8f8f8;font-size:12px;font-weight:bold;color:#666;width:35%;border-bottom:1px solid #eee">${k}</td>
                  <td style="padding:8px;font-size:14px;color:#1a1a2e;border-bottom:1px solid #eee">${esc(v)}</td>
                </tr>`,
              )
              .join("")}
          </table>
          <p style="margin-top:16px;font-size:13px;color:#444">
            Open <strong>/rental-admin → Disputes</strong>, click <strong>Build evidence pack</strong>,
            review the draft, then <strong>Submit to bank</strong> before the deadline.
            Missing the deadline loses the dispute automatically.
          </p>
        </div>
      </div>`,
    )
  } catch (e) {
    console.error("Dispute alert email error:", e)
  }
}
